-- Tabellen für das Soldaten-Backend. Das Skript ist wiederholbar.
CREATE SCHEMA IF NOT EXISTS soldat;

DO $$
BEGIN
    CREATE TYPE soldat.geschlecht AS ENUM ('MAENNLICH', 'WEIBLICH');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$
BEGIN
    CREATE TYPE soldat.rang AS ENUM ('REKRUT', 'SOLDAT', 'CAPTAIN');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$
BEGIN
    CREATE TYPE soldat.waffe AS ENUM ('Klinge', 'Schrotflinte', 'ODM_GEAR');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$
BEGIN
    CREATE TYPE soldat.schweregrad AS ENUM ('LEICHT', 'MITTEL', 'SCHWER');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS soldat.soldat (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0),
    vorname VARCHAR(80) NOT NULL CHECK (length(btrim(vorname)) > 0),
    nachname VARCHAR(80) NOT NULL CHECK (length(btrim(nachname)) > 0),
    geburtsdatum DATE NOT NULL,
    geschlecht soldat.geschlecht NOT NULL,
    rang soldat.rang NOT NULL,
    username VARCHAR(50) NOT NULL UNIQUE,
    erzeugt TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    aktualisiert TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS soldat.ausruestung (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    waffe soldat.waffe NOT NULL,
    seriennummer VARCHAR(30) NOT NULL UNIQUE CHECK (seriennummer ~ '^AOT-[A-Za-z0-9]+$'),
    soldat_id INTEGER NOT NULL UNIQUE REFERENCES soldat.soldat(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS soldat.verletzung (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    verletzungsbezeichnung VARCHAR(200) NOT NULL CHECK (length(btrim(verletzungsbezeichnung)) > 0),
    behandelt BOOLEAN NOT NULL,
    schweregrad soldat.schweregrad NOT NULL,
    verletzungsdatum DATE NOT NULL,
    soldat_id INTEGER NOT NULL REFERENCES soldat.soldat(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_ausruestung_soldat_id ON soldat.ausruestung(soldat_id);
CREATE INDEX IF NOT EXISTS ix_verletzung_soldat_id ON soldat.verletzung(soldat_id);
CREATE INDEX IF NOT EXISTS ix_verletzung_schweregrad ON soldat.verletzung(schweregrad);

